def main():
    if not TOKEN:
        print("متغیر BALE_TOKEN تنظیم نشده است.")
        return
    base_url = f"https://tapi.bale.ai/bot{TOKEN}"
    offset = 0
    while True:
        try:
            response = requests.get(
                f"{base_url}/getUpdates",
                params={"offset": offset, "timeout": 30},
                timeout=35,
            )
            response.raise_for_status()
            updates = response.json().get("result", [])
            for update in updates:
                offset = update["update_id"] + 1
                message = update.get("message", {})
                chat_id = message.get("chat", {}).get("id")
                user_text = message.get("text", "").strip()
                if not chat_id or not user_text:
                    continue
                if user_text == "/start":
                    answer = (
                        "سلام! به ربات سرفصل‌های بانکی خوش اومدی.\n"
                        "کد عددی یا کد اختصاری رو بفرست تا جست‌وجو کنم."
                    )
                else:
                    item = ACCOUNTS.get(user_text)
                    if not item:
                        item = next(
                            (
                                value
                                for value in ACCOUNTS.values()
                                if value[0].lower() == user_text.lower()
                            ),
                            None,
                        )
                    if item:
                        numeric_code = next(
                            (
                                code
                                for code, value in ACCOUNTS.items()
                                if value == item
                            ),
                            "نامشخص",
                        )
                        answer = (
                            f"کد عددی: {numeric_code}\n"
                            f"کد اختصاری: {item[0]}\n"
                            f"سرفصل: {item[1]}"
                        )
                    else:
                        answer = "این کد در فهرست فعلی پیدا نشد."
                requests.post(
                    f"{base_url}/sendMessage",
                    json={"chat_id": chat_id, "text": answer},
                    timeout=20,
                )
        except requests.RequestException as error:
            print("خطای ارتباط:", error)
            time.sleep(5)
        except Exception as error:
            print("خطا:", error)
            time.sleep(5)
if __name__ == "__main__":
    main()
